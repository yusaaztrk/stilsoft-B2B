using Microsoft.AspNetCore.Authorization;
using Microsoft.AspNetCore.Mvc;
using Microsoft.EntityFrameworkCore;
using Npgsql;
using ServiceOps.Infrastructure.Data;
using System.Security.Claims;
using System.Text.Json.Serialization;

namespace ServiceOps.Api.Controllers
{
    public class LocationRequest
    {
        [JsonPropertyName("latitude")]
        public double Latitude { get; set; }
        
        [JsonPropertyName("longitude")]
        public double Longitude { get; set; }
        
        [JsonPropertyName("timestampUtc")]
        public DateTime TimestampUtc { get; set; }
    }

    [ApiController]
    [Route("api/technicians")]
    [Authorize]
    public class LocationController : ControllerBase
    {
        private readonly IConfiguration _config;
        public LocationController(IConfiguration config)
        {
            _config = config;
        }

        [HttpPost("location")]
        public async Task<IActionResult> UpdateLocation([FromBody] LocationRequest request, CancellationToken ct)
        {
            var tenantCode = User.FindFirst("tenant")?.Value ?? string.Empty;
            var username = User.Identity?.Name ?? string.Empty;

            if (string.IsNullOrWhiteSpace(tenantCode) || string.IsNullOrWhiteSpace(username))
                return Unauthorized();

            var dbName = $"b2b_serviceops_tenant_{tenantCode}";
            var connTemplate = _config.GetConnectionString("ServiceOpsBase");
            if (string.IsNullOrWhiteSpace(connTemplate)) return StatusCode(500, "Connection string base not found");

            var connStr = connTemplate.Replace("{DB_NAME}", dbName);
            
            await using var conn = new NpgsqlConnection(connStr);
            try
            {
                await conn.OpenAsync(ct);
            }
            catch
            {
                return BadRequest("Tenant DB not found");
            }

            // Create table if not exists
            await using (var createCmd = conn.CreateCommand())
            {
                createCmd.CommandText = @"
                CREATE TABLE IF NOT EXISTS public.""TechnicianLocations"" (
                    ""Id"" integer GENERATED BY DEFAULT AS IDENTITY,
                    ""Username"" character varying(100) NOT NULL,
                    ""Latitude"" double precision NOT NULL,
                    ""Longitude"" double precision NOT NULL,
                    ""TimestampUtc"" timestamp with time zone NOT NULL,
                    CONSTRAINT ""PK_TechnicianLocations"" PRIMARY KEY (""Id"")
                );
                CREATE INDEX IF NOT EXISTS ""IX_TechnicianLocations_Username"" ON public.""TechnicianLocations"" (""Username"");
                CREATE INDEX IF NOT EXISTS ""IX_TechnicianLocations_Timestamp"" ON public.""TechnicianLocations"" (""TimestampUtc"" DESC);
                ";
                await createCmd.ExecuteNonQueryAsync(ct);
            }

            await using (var insertCmd = conn.CreateCommand())
            {
                insertCmd.CommandText = @"
                INSERT INTO public.""TechnicianLocations"" (""Username"", ""Latitude"", ""Longitude"", ""TimestampUtc"")
                VALUES (@u, @lat, @lon, @ts);
                ";
                insertCmd.Parameters.AddWithValue("u", username);
                insertCmd.Parameters.AddWithValue("lat", request.Latitude);
                insertCmd.Parameters.AddWithValue("lon", request.Longitude);
                insertCmd.Parameters.AddWithValue("ts", DateTime.SpecifyKind(request.TimestampUtc, DateTimeKind.Utc));
                await insertCmd.ExecuteNonQueryAsync(ct);
            }

            return Ok(new { success = true });
        }
    }
}
