using System;
using System.IO;
using System.Linq;
using System.Net;
using System.Security.Claims;
using System.Text.Json;
using System.Threading.Tasks;
using Microsoft.AspNetCore.Http;
using Microsoft.Extensions.DependencyInjection;
using Microsoft.Extensions.Logging;
using Microsoft.EntityFrameworkCore;
using ServiceOps.Infrastructure.Data;

namespace ServiceOps.Api.Middleware
{
    public sealed class GlobalExceptionMiddleware
    {
        private readonly RequestDelegate _next;
        private readonly ILogger<GlobalExceptionMiddleware> _logger;
        private readonly IServiceScopeFactory _scopeFactory;

        public GlobalExceptionMiddleware(RequestDelegate next, ILogger<GlobalExceptionMiddleware> logger, IServiceScopeFactory scopeFactory)
        {
            _next = next;
            _logger = logger;
            _scopeFactory = scopeFactory;
        }

        public async Task InvokeAsync(HttpContext context)
        {
            try
            {
                await _next(context);
            }
            catch (Exception ex)
            {
                _logger.LogError(ex, "[ServiceOps GlobalExceptionMiddleware caught exception]: {Message}", ex.Message);
                await LogExceptionToDatabaseAsync(context, ex);
                await HandleResponseAsync(context, ex);
            }
        }

        private async Task LogExceptionToDatabaseAsync(HttpContext context, Exception ex)
        {
            try
            {
                using var scope = _scopeFactory.CreateScope();
                var dbContext = scope.ServiceProvider.GetRequiredService<ApplicationDbContext>();

                var user = context.User;
                string username = user.FindFirst("username")?.Value 
                    ?? user.FindFirst(ClaimTypes.Name)?.Value 
                    ?? user.FindFirst(ClaimTypes.NameIdentifier)?.Value 
                    ?? "AnonimTeknisyen";

                string userDisplayName = user.FindFirst("unvan")?.Value 
                    ?? user.FindFirst("fullName")?.Value 
                    ?? username;

                string roleName = user.FindFirst("role")?.Value 
                    ?? user.FindFirst(ClaimTypes.Role)?.Value 
                    ?? "Technician";

                string ip = context.Connection.RemoteIpAddress?.ToString() ?? "";
                if (context.Request.Headers.TryGetValue("X-Forwarded-For", out var fwd))
                {
                    ip = fwd.ToString().Split(',')[0].Trim();
                }

                string? innerMsg = ex.InnerException?.Message;
                if (ex.InnerException?.InnerException != null)
                {
                    innerMsg += " ---> " + ex.InnerException.InnerException.Message;
                }

                string tenantCode = context.Request.Headers["X-Tenant-Code"].FirstOrDefault() 
                    ?? user.FindFirst("TenantCode")?.Value 
                    ?? user.FindFirst("tenantCode")?.Value 
                    ?? "DEMO";

                string sql = @"
                CREATE TABLE IF NOT EXISTS ""SystemErrorLogs"" (
                    ""Id"" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    ""CreatedAt"" timestamp with time zone NOT NULL,
                    ""LocalTime"" timestamp without time zone NOT NULL,
                    ""UserId"" integer NULL,
                    ""Username"" text NOT NULL,
                    ""UserDisplayName"" text NOT NULL,
                    ""RoleName"" text NOT NULL,
                    ""CariKodu"" text NULL,
                    ""UserIp"" text NOT NULL,
                    ""HttpMethod"" text NOT NULL,
                    ""RequestPath"" text NOT NULL,
                    ""QueryString"" text NULL,
                    ""RequestBodySummary"" text NULL,
                    ""ExceptionType"" text NOT NULL,
                    ""ErrorMessage"" text NOT NULL,
                    ""InnerExceptionMessage"" text NULL,
                    ""StackTrace"" text NULL,
                    ""StatusCode"" integer NOT NULL,
                    ""SourceModule"" text NOT NULL,
                    ""TenantCode"" text NOT NULL,
                    ""IsResolved"" boolean NOT NULL DEFAULT FALSE,
                    ""ResolutionNotes"" text NULL,
                    ""ResolvedAt"" timestamp with time zone NULL,
                    ""ResolvedBy"" text NULL
                );

                INSERT INTO ""SystemErrorLogs"" (
                    ""CreatedAt"", ""LocalTime"", ""Username"", ""UserDisplayName"", ""RoleName"", ""UserIp"",
                    ""HttpMethod"", ""RequestPath"", ""QueryString"", ""ExceptionType"", ""ErrorMessage"",
                    ""InnerExceptionMessage"", ""StackTrace"", ""StatusCode"", ""SourceModule"", ""TenantCode"", ""IsResolved""
                ) VALUES (
                    @p0, @p1, @p2, @p3, @p4, @p5, @p6, @p7, @p8, @p9, @p10, @p11, @p12, @p13, @p14, @p15, FALSE
                );";

                await dbContext.Database.ExecuteSqlRawAsync(sql,
                    DateTime.UtcNow,
                    DateTime.Now,
                    username,
                    userDisplayName,
                    roleName,
                    ip,
                    context.Request.Method,
                    context.Request.Path.Value ?? "",
                    context.Request.QueryString.HasValue ? context.Request.QueryString.Value : (object)DBNull.Value,
                    ex.GetType().FullName ?? ex.GetType().Name,
                    ex.Message,
                    innerMsg ?? (object)DBNull.Value,
                    ex.StackTrace ?? (object)DBNull.Value,
                    context.Response.StatusCode == 200 ? 500 : context.Response.StatusCode,
                    "ServiceOps.Api",
                    tenantCode
                );
            }
            catch (Exception dbEx)
            {
                _logger.LogError(dbEx, "[ServiceOps GlobalExceptionMiddleware - Failed to save error log]: {Message}", dbEx.Message);
            }
        }

        private static async Task HandleResponseAsync(HttpContext context, Exception ex)
        {
            if (!context.Response.HasStarted)
            {
                context.Response.ContentType = "application/json";
                context.Response.StatusCode = (int)HttpStatusCode.InternalServerError;

                var responsePayload = new
                {
                    success = false,
                    message = $"ServiceOps hatası oluştu ve loglandı: {ex.Message}",
                    errorType = ex.GetType().Name,
                    path = context.Request.Path.Value,
                    timestamp = DateTime.Now.ToString("dd.MM.yyyy HH:mm:ss")
                };

                var options = new JsonSerializerOptions { PropertyNamingPolicy = JsonNamingPolicy.CamelCase };
                await context.Response.WriteAsync(JsonSerializer.Serialize(responsePayload, options));
            }
        }
    }
}
