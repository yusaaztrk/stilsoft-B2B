using System.Collections.Concurrent;
using B2B.Erp.Api.Data;
using Microsoft.EntityFrameworkCore;

namespace B2B.Erp.Api.Core.Services;

/// <summary>
/// `SystemErrorLogs` tablosunun şemasını garanti eder — VERİTABANI BAŞINA BİR KEZ.
///
/// Öncesinde hem `GlobalExceptionMiddleware` her hata kaydında hem de `SystemErrorLogsController`
/// her listeleme isteğinde `CREATE TABLE IF NOT EXISTS` + dokuz `ALTER TABLE ... IF NOT EXISTS`
/// çalıştırıyordu. Bu komutlar hiçbir şeyi değiştirmese bile PostgreSQL katalog kilidi alır:
/// bir hata dalgasında (yanlış şifre denemeleri, bozuk id ile gelen istekler) saniyede yüzlerce
/// DDL veritabanına gidiyor ve asıl işi yapan sorguları bekletiyordu.
///
/// Tablo çok kiracılı: her kiracının kendi veritabanı var, o yüzden nöbetçi bağlantı dizesine
/// göre tutuluyor — yeni bir kiracı veritabanı ilk kullanımda yine kurulur.
/// </summary>
public static class SystemErrorLogSchema
{
    private static readonly ConcurrentDictionary<string, bool> EnsuredDatabases = new();

    private const string Ddl = @"
CREATE TABLE IF NOT EXISTS ""SystemErrorLogs"" (
    ""Id"" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ""CreatedAt"" timestamp with time zone NOT NULL,
    ""LocalTime"" timestamp without time zone NOT NULL,
    ""UserId"" integer NULL,
    ""Username"" text NOT NULL,
    ""UserDisplayName"" text NOT NULL,
    ""RoleName"" text NOT NULL,
    ""CariKodu"" text NULL,
    ""UserIp"" text NOT NULL,
    ""HttpMethod"" text NOT NULL,
    ""RequestPath"" text NOT NULL,
    ""QueryString"" text NULL,
    ""RequestBodySummary"" text NULL,
    ""ExceptionType"" text NOT NULL,
    ""ErrorMessage"" text NOT NULL,
    ""InnerExceptionMessage"" text NULL,
    ""StackTrace"" text NULL,
    ""StatusCode"" integer NOT NULL,
    ""SourceModule"" text NOT NULL,
    ""TenantCode"" text NOT NULL,
    ""IsResolved"" boolean NOT NULL DEFAULT FALSE,
    ""ResolutionNotes"" text NULL,
    ""ResolvedAt"" timestamp with time zone NULL,
    ""ResolvedBy"" text NULL
);
ALTER TABLE ""SystemErrorLogs"" ADD COLUMN IF NOT EXISTS ""RequestBodySummary"" text NULL;
ALTER TABLE ""SystemErrorLogs"" ADD COLUMN IF NOT EXISTS ""InnerExceptionMessage"" text NULL;
ALTER TABLE ""SystemErrorLogs"" ADD COLUMN IF NOT EXISTS ""StackTrace"" text NULL;
ALTER TABLE ""SystemErrorLogs"" ADD COLUMN IF NOT EXISTS ""SourceModule"" text NOT NULL DEFAULT 'B2B.Erp.Api';
ALTER TABLE ""SystemErrorLogs"" ADD COLUMN IF NOT EXISTS ""TenantCode"" text NOT NULL DEFAULT 'DEMO';
ALTER TABLE ""SystemErrorLogs"" ADD COLUMN IF NOT EXISTS ""IsResolved"" boolean NOT NULL DEFAULT FALSE;
ALTER TABLE ""SystemErrorLogs"" ADD COLUMN IF NOT EXISTS ""ResolutionNotes"" text NULL;
ALTER TABLE ""SystemErrorLogs"" ADD COLUMN IF NOT EXISTS ""ResolvedAt"" timestamp with time zone NULL;
ALTER TABLE ""SystemErrorLogs"" ADD COLUMN IF NOT EXISTS ""ResolvedBy"" text NULL;";

    public static async Task EnsureAsync(AppDbContext dbContext, CancellationToken cancellationToken = default)
    {
        var key = dbContext.Database.GetConnectionString() ?? "default";
        if (EnsuredDatabases.ContainsKey(key)) return;

        try
        {
            await dbContext.Database.ExecuteSqlRawAsync(Ddl, cancellationToken);
            EnsuredDatabases[key] = true;
        }
        catch
        {
            // Şema kurulamadıysa nöbetçiye YAZMA: bir sonraki istek tekrar denesin. Hata
            // kaydının kendisi zaten sessizce düşüyor; burada patlamak asıl isteği bozardı.
        }
    }
}
