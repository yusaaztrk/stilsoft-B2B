using B2B.Erp.Api.Data;
using B2B.Erp.Api.Entities;
using Microsoft.AspNetCore.Authorization;
using Microsoft.AspNetCore.Mvc;
using Microsoft.EntityFrameworkCore;
using System.ComponentModel.DataAnnotations;

namespace B2B.Erp.Api.Controllers;

[ApiController]
[Route("api/[controller]")]
[Authorize]
public sealed class CheckBranchesController : ControllerBase
{
    private readonly AppDbContext _dbContext;

    public CheckBranchesController(AppDbContext dbContext)
    {
        _dbContext = dbContext;
    }

    /// <summary>
    /// Şema + tohum işi VERİTABANI BAŞINA BİR KEZ çalışır.
    ///
    /// Bu metot listeleme, ekleme ve güncelleme uçlarının BAŞINDA çağrılıyor; her istekte bir
    /// `CREATE TABLE IF NOT EXISTS` (PostgreSQL katalog kilidi) ve ardından tüm şube adlarının
    /// belleğe çekilip 49 sabitle karşılaştırılması demekti. Şube listesi neredeyse hiç
    /// değişmiyor; nöbetçi bağlantı dizesine göre tutuluyor çünkü her firmanın kendi
    /// veritabanı var (yeni firma ilk kullanımda yine tohumlanır).
    /// </summary>
    private static readonly System.Collections.Concurrent.ConcurrentDictionary<string, bool> SeededDatabases = new();

    private async Task EnsureDefaultBranchesAsync(CancellationToken cancellationToken)
    {
        var seedKey = _dbContext.Database.GetConnectionString() ?? "default";
        if (SeededDatabases.ContainsKey(seedKey)) return;

        var sql = @"
CREATE TABLE IF NOT EXISTS ""CheckBranches"" (
    ""Id"" integer GENERATED BY DEFAULT AS IDENTITY,
    ""Name"" character varying(100) NOT NULL,
    ""IsActive"" boolean NOT NULL DEFAULT true,
    ""CreatedAt"" timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ""PK_CheckBranches"" PRIMARY KEY (""Id"")
);";
        await _dbContext.Database.ExecuteSqlRawAsync(sql, cancellationToken);

        var allBranches = new[]
        {
            "AKDOĞAN", "ALAYKÖY", "ALSANCAK", "BOSTANCI", "BOĞAZ", "DEREBOYU",
            "DEĞİRMENLİK", "DİKİLİTAŞ", "DİKMEN", "DOĞANCI", "ERÜLKÜ", "ESENTEPE",
            "GAZİMAĞUSA", "GAZİMAĞUSA MARAŞ", "GAZİMAĞUSA MERKEZ", "GEMİKONAĞI", "GEÇİTKALE",
            "GİRNE", "GİRNE PARK AVM", "GİRNE ÇARŞI", "GÖNYELİ", "GÖÇMENKÖY", "GÜZELYURT",
            "İSKELE", "KARAKUM", "KARAOĞLANOĞLU", "KÖŞKLÜÇİFTLİK", "KÜÇÜK KAYMAKLI",
            "LAPTA", "LEFKOŞA", "LEFKOŞA MERKEZ", "LEFKOŞA SANAYİ", "MEHMETÇİK", "MERKEZ",
            "ORGANİZE SANAYİ", "OZANKÖY", "SALAMİS YOLU", "SANAYİ", "SARAYÖNÜ", "SERDARLI",
            "TAŞKINKÖY", "TERMİNAL", "YENİ ERENKÖY", "YENİ İSKELE", "YENİBOĞAZİÇİ",
            "YENİKENT", "YENİŞEHİR", "ÇATALKÖY", "ÇAYÖNÜ"
        };

        var currentBranchNames = await _dbContext.CheckBranches
            .Select(x => x.Name)
            .ToListAsync(cancellationToken);

        // EKSİK OLANI EKLE — TABLOYU SIFIRLAMA.
        //
        // Burada `Count != 49 || beklenmeyen isim var` koşuluyla `TRUNCATE` çalışıyordu:
        // kullanıcı `Create` ucuyla yeni bir şube eklediği anda sayı 50 oluyor ve bir sonraki
        // LİSTELEME isteğinde (bu metot `GetAll`ın başında çağrılıyor) eklediği şube kalıcı
        // olarak siliniyordu. Tohumlama, kullanıcı verisini silme yetkisi olmayan bir
        // "eksikleri tamamla" işidir.
        var existingNames = new HashSet<string>(currentBranchNames, StringComparer.OrdinalIgnoreCase);
        var missing = allBranches.Where(name => !existingNames.Contains(name)).ToList();

        if (missing.Count > 0)
        {
            foreach (var name in missing)
            {
                _dbContext.CheckBranches.Add(new CheckBranch
                {
                    Name = name,
                    IsActive = true,
                    CreatedAt = DateTime.UtcNow
                });
            }
            await _dbContext.SaveChangesAsync(cancellationToken);
        }

        SeededDatabases[seedKey] = true;
    }

    [HttpGet]
    public async Task<IActionResult> GetAll(CancellationToken cancellationToken = default)
    {
        await EnsureDefaultBranchesAsync(cancellationToken);

        var data = await _dbContext.CheckBranches
            .AsNoTracking()
            .OrderBy(x => x.Name)
            .Select(x => new
            {
                id = x.Id,
                name = x.Name,
                isActive = x.IsActive,
                createdAt = x.CreatedAt
            })
            .ToListAsync(cancellationToken);

        return Ok(new { success = true, data });
    }

    [HttpGet("dropdown")]
    public async Task<IActionResult> GetDropdown(CancellationToken cancellationToken = default)
    {
        await EnsureDefaultBranchesAsync(cancellationToken);

        var data = await _dbContext.CheckBranches
            .AsNoTracking()
            .Where(x => x.IsActive)
            .OrderBy(x => x.Name)
            .Select(x => new
            {
                id = x.Id,
                name = x.Name
            })
            .ToListAsync(cancellationToken);

        return Ok(new { success = true, data });
    }

    public sealed class CreateBranchRequest
    {
        [Required]
        [StringLength(100)]
        public string Name { get; set; } = string.Empty;
        public bool IsActive { get; set; } = true;
    }

    [HttpPost]
    public async Task<IActionResult> Create([FromBody] CreateBranchRequest request, CancellationToken cancellationToken = default)
    {
        await EnsureDefaultBranchesAsync(cancellationToken);
        var nameClean = (request.Name ?? string.Empty).Trim();
        if (string.IsNullOrWhiteSpace(nameClean))
        {
            return BadRequest(new { success = false, message = "Şube adı zorunludur." });
        }

        var exists = await _dbContext.CheckBranches
            .AnyAsync(x => x.Name.ToLower() == nameClean.ToLower(), cancellationToken);

        if (exists)
        {
            return BadRequest(new { success = false, message = "Bu şube adı zaten mevcut." });
        }

        var entity = new CheckBranch
        {
            Name = nameClean,
            IsActive = request.IsActive,
            CreatedAt = DateTime.UtcNow
        };

        _dbContext.CheckBranches.Add(entity);
        await _dbContext.SaveChangesAsync(cancellationToken);

        return Ok(new { success = true, data = new { id = entity.Id, name = entity.Name, isActive = entity.IsActive } });
    }

    public sealed class UpdateBranchRequest
    {
        [Required]
        [StringLength(100)]
        public string Name { get; set; } = string.Empty;
        public bool IsActive { get; set; } = true;
    }

    [HttpPut("{id}")]
    public async Task<IActionResult> Update([FromRoute] int id, [FromBody] UpdateBranchRequest request, CancellationToken cancellationToken = default)
    {
        var entity = await _dbContext.CheckBranches.FirstOrDefaultAsync(x => x.Id == id, cancellationToken);
        if (entity == null)
        {
            return NotFound(new { success = false, message = "Şube bulunamadı." });
        }

        var nameClean = (request.Name ?? string.Empty).Trim();
        if (string.IsNullOrWhiteSpace(nameClean))
        {
            return BadRequest(new { success = false, message = "Şube adı zorunludur." });
        }

        var exists = await _dbContext.CheckBranches
            .AnyAsync(x => x.Id != id && x.Name.ToLower() == nameClean.ToLower(), cancellationToken);

        if (exists)
        {
            return BadRequest(new { success = false, message = "Bu şube adı başka bir kayıtta mevcut." });
        }

        entity.Name = nameClean;
        entity.IsActive = request.IsActive;

        await _dbContext.SaveChangesAsync(cancellationToken);

        return Ok(new { success = true, data = new { id = entity.Id, name = entity.Name, isActive = entity.IsActive } });
    }

    [HttpDelete("{id}")]
    public async Task<IActionResult> Delete([FromRoute] int id, CancellationToken cancellationToken = default)
    {
        var entity = await _dbContext.CheckBranches.FirstOrDefaultAsync(x => x.Id == id, cancellationToken);
        if (entity == null)
        {
            return NotFound(new { success = false, message = "Şube bulunamadı." });
        }

        _dbContext.CheckBranches.Remove(entity);
        await _dbContext.SaveChangesAsync(cancellationToken);

        return Ok(new { success = true, message = "Şube silindi." });
    }
}
