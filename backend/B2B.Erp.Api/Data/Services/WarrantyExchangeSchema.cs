/// <summary>
/// Garanti değişim tablolarının + sayfalarının kurulum SQL'i.
///
/// Bu depoda tablo eklemenin yolu <c>dotnet ef migrations add</c> DEĞİL (snapshot kayması
/// alakasız onlarca işlem üretiyor); açılışta koşan <c>IF NOT EXISTS</c> SQL'i.
/// Aynı desen <see cref="LoanSchema"/> ve <see cref="EcommerceSchema"/>'da da var.
///
/// Metin TEK YERDE duruyor çünkü iki yerden çalıştırılıyor: varsayılan veritabanı için
/// <c>Program.cs</c>, her firma veritabanı için <c>TenantConnectionStringResolver</c>.
/// SQL'i iki bloğa elle kopyalamak bu depoda tekrarlayan bir hata kaynağı.
/// </summary>
public static class WarrantyExchangeSchema
{
    public const string WarrantyExchangeDdl = @"
DO $$
BEGIN

CREATE TABLE IF NOT EXISTS ""WarrantyExchangeSettings"" (
  ""Id"" integer NOT NULL,
  ""WarehouseCode"" integer NOT NULL DEFAULT 0,
  ""CreateUser"" character varying(50) NOT NULL DEFAULT '',
  ""CreateTime"" timestamp with time zone NOT NULL DEFAULT now(),
  ""EditUser"" character varying(50) NULL,
  ""EditTime"" timestamp with time zone NULL,
  CONSTRAINT ""PK_WarrantyExchangeSettings"" PRIMARY KEY (""Id""),
  -- TEK SATIR. Ikinci satir ""hangisi gecerli"" sorusunu dogurur ve ekran sessizce yanlis
  -- depoya yazar; kural veritabaninda zorlaniyor.
  CONSTRAINT ""CK_WarrantyExchangeSettings_SingleRow"" CHECK (""Id"" = 1)
);

INSERT INTO ""WarrantyExchangeSettings"" (""Id"", ""WarehouseCode"", ""CreateUser"", ""CreateTime"")
SELECT 1, 0, 'System', now()
WHERE NOT EXISTS (SELECT 1 FROM ""WarrantyExchangeSettings"" WHERE ""Id"" = 1);

CREATE TABLE IF NOT EXISTS ""WarrantyExchanges"" (
  ""Id"" integer GENERATED BY DEFAULT AS IDENTITY,
  ""ExchangeNo"" character varying(30) NOT NULL,
  ""Date"" timestamp with time zone NOT NULL,
  ""CustomerCode"" character varying(50) NOT NULL,
  ""InvoiceNo"" character varying(50) NULL,
  -- Ayar sonradan degisirse eski kayitlarin hangi depoya girdigi kaybolmasin diye
  -- islem anindaki depo damgalanir.
  ""WarrantyWarehouseCode"" integer NOT NULL DEFAULT 0,
  ""OutWarehouseCode"" integer NOT NULL DEFAULT 0,
  ""ReturnedStockCode"" character varying(50) NOT NULL DEFAULT '',
  ""ReturnedProductName"" character varying(300) NULL,
  ""ReturnedQuantity"" numeric(18,3) NOT NULL DEFAULT 0,
  ""ReturnedUnitPrice"" numeric(18,2) NOT NULL DEFAULT 0,
  ""ReturnedSerialNo"" character varying(100) NULL,
  ""GivenStockCode"" character varying(50) NOT NULL DEFAULT '',
  ""GivenProductName"" character varying(300) NULL,
  ""GivenQuantity"" numeric(18,3) NOT NULL DEFAULT 0,
  ""GivenUnitPrice"" numeric(18,2) NOT NULL DEFAULT 0,
  ""GivenSerialNo"" character varying(100) NULL,
  ""DiscountAmount"" numeric(18,2) NOT NULL DEFAULT 0,
  ""CurrencyTypeId"" integer NOT NULL DEFAULT 0,
  ""CurrencyRate"" numeric(18,6) NOT NULL DEFAULT 1,
  ""CustomerLedgerEntryId"" integer NULL,
  ""Description"" character varying(2000) NULL,
  ""CreateUser"" character varying(50) NOT NULL DEFAULT '',
  ""CreateTime"" timestamp with time zone NOT NULL DEFAULT now(),
  ""EditUser"" character varying(50) NULL,
  ""EditTime"" timestamp with time zone NULL,
  CONSTRAINT ""PK_WarrantyExchanges"" PRIMARY KEY (""Id"")
);

CREATE UNIQUE INDEX IF NOT EXISTS ""UX_WarrantyExchanges_ExchangeNo""
  ON ""WarrantyExchanges"" (""ExchangeNo"");
CREATE INDEX IF NOT EXISTS ""IX_WarrantyExchanges_CustomerCode_Date""
  ON ""WarrantyExchanges"" (""CustomerCode"", ""Date"");
CREATE INDEX IF NOT EXISTS ""IX_WarrantyExchanges_Date"" ON ""WarrantyExchanges"" (""Date"");

-- Tablo ustteki blokla ZATEN kurulmus firmalarda yeni kolonlar CREATE TABLE ile gelmez
-- (IF NOT EXISTS oldugu icin tablo atlanir). Sonradan eklenen her alan ayrica ALTER ile
-- de yazilmali; aksi halde eski firmalarda her istek 42703 ile duser.
ALTER TABLE ""WarrantyExchanges"" ADD COLUMN IF NOT EXISTS ""ReturnedSerialNo"" character varying(100) NULL;
ALTER TABLE ""WarrantyExchanges"" ADD COLUMN IF NOT EXISTS ""GivenSerialNo"" character varying(100) NULL;
ALTER TABLE ""WarrantyExchanges"" ADD COLUMN IF NOT EXISTS ""CustomerLedgerEntryId"" integer NULL;

-- Sayfalar. Sayfa anahtari olmadan rol yetkilerinde gorunmez ve AuthorizePage her istegi
-- reddeder.
IF EXISTS (
  SELECT 1 FROM information_schema.tables
  WHERE table_schema='public' AND table_name='Pages'
) THEN

  -- SAYFA KIMLIGI SABIT YAZILAMAZ.
  --
  -- Ayni kimlik her veritabaninda BASKA bir sayfaya ait (20002 ana DB'de
  -- reports/virmanRaporlari, DEMOTEST'te users/genelAyarlar). Sabit kimlik PK_Pages'i
  -- ihlal eder ve hata BU BLOGUN TAMAMINI dusurur -- tablolar bile olusmaz (LoanSchema'da
  -- bir kez yasandi, 2026-08-12). O yuzden kimlik her veritabaninda MAX+1'den hesaplaniyor.

  -- 1) Ayarlar -> Garanti Deposu. Hangi deponun garanti deposu oldugu buradan secilir.
  INSERT INTO ""Pages"" (""Id"", ""DisplayName"", ""IsActive"", ""Key"", ""ModuleKey"", ""SortOrder"")
  SELECT (SELECT COALESCE(MAX(""Id""), 0) + 1 FROM ""Pages""), 'Garanti Deposu', TRUE, 'garantiDeposu', 'users', 23
  WHERE NOT EXISTS (
    SELECT 1 FROM ""Pages"" WHERE ""ModuleKey""='users' AND ""Key""='garantiDeposu'
  );

  -- 2) Fatura Islemleri -> Garanti Degisim. Islemin kendisi.
  INSERT INTO ""Pages"" (""Id"", ""DisplayName"", ""IsActive"", ""Key"", ""ModuleKey"", ""SortOrder"")
  SELECT (SELECT COALESCE(MAX(""Id""), 0) + 1 FROM ""Pages""), 'Garanti Değişim', TRUE, 'garantiDegisim', 'invoice', 18
  WHERE NOT EXISTS (
    SELECT 1 FROM ""Pages"" WHERE ""ModuleKey""='invoice' AND ""Key""='garantiDegisim'
  );

  -- 2b) Fatura Islemleri -> Garanti Degisim -> Sil (Alt yetki)
  INSERT INTO ""Pages"" (""Id"", ""DisplayName"", ""IsActive"", ""Key"", ""ModuleKey"", ""SortOrder"")
  SELECT (SELECT COALESCE(MAX(""Id""), 0) + 1 FROM ""Pages""), 'Sil', TRUE, 'garantiDegisimSil', 'invoice', 19
  WHERE NOT EXISTS (
    SELECT 1 FROM ""Pages"" WHERE ""ModuleKey""='invoice' AND ""Key""='garantiDegisimSil'
  );

  -- 3) Raporlar -> Garanti Degisim Raporu.
  --
  -- ADI ""Garanti Raporlari"" DEGIL: o anahtar (reports/garantiRaporlari, Id 501) zaten
  -- WarrantyRecords tabanli garanti KAYIT takibinde kullaniliyor. Ayni anahtari ikinci kez
  -- yazmak tekil indeksi patlatir, ayni adi vermek de iki farkli raporu karistirir.
  INSERT INTO ""Pages"" (""Id"", ""DisplayName"", ""IsActive"", ""Key"", ""ModuleKey"", ""SortOrder"")
  SELECT (SELECT COALESCE(MAX(""Id""), 0) + 1 FROM ""Pages""), 'Garanti Değişim Raporu', TRUE, 'garantiDegisimRaporu', 'reports', 20
  WHERE NOT EXISTS (
    SELECT 1 FROM ""Pages"" WHERE ""ModuleKey""='reports' AND ""Key""='garantiDegisimRaporu'
  );

  IF EXISTS (
    SELECT 1 FROM information_schema.tables
    WHERE table_schema='public' AND table_name='RolePagePermissions'
  ) THEN

    -- ISLEM + RAPOR: 1 SuperAdmin, 2 Yonetim, 3 Mudur.
    -- Diger roller BILEREK disarida; gerekirse Rol Yetkileri ekranindan acilir. Kodda
    -- hicbir rol sabiti yok, kapi tamamen bu tablodan.
    INSERT INTO ""RolePagePermissions"" (""RoleId"", ""PageId"", ""CanAccess"")
    SELECT r.""Id"", p.""Id"", TRUE
    FROM ""Roles"" r
    CROSS JOIN (
      SELECT ""Id"" FROM ""Pages""
      WHERE (""ModuleKey""='invoice' AND ""Key"" IN ('garantiDegisim', 'garantiDegisimSil'))
         OR (""ModuleKey""='reports' AND ""Key""='garantiDegisimRaporu')
    ) p
    WHERE r.""Id"" IN (1,2,3)
    ON CONFLICT (""RoleId"", ""PageId"") DO NOTHING;

    -- AYAR SAYFASI YALNIZCA SUPERADMIN (1).
    -- Kullanicinin karari: Yonetim islem ve raporu gorur ama garanti deposunu degistiremez.
    -- Ayar tek satir ve butun gecmisi etkiliyor; iki kisinin ayni anda oynadigi bir alan degil.
    INSERT INTO ""RolePagePermissions"" (""RoleId"", ""PageId"", ""CanAccess"")
    SELECT r.""Id"", p.""Id"", TRUE
    FROM ""Roles"" r
    CROSS JOIN (
      SELECT ""Id"" FROM ""Pages"" WHERE ""ModuleKey""='users' AND ""Key""='garantiDeposu'
    ) p
    WHERE r.""Id"" IN (1)
    ON CONFLICT (""RoleId"", ""PageId"") DO NOTHING;

  END IF;

END IF;
END $$;
";
}
