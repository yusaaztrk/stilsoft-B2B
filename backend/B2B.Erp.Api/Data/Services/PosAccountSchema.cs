namespace B2B.Erp.Api.Data.Services;

/// <summary>
/// Schema for the POS account sweep feature.
///
/// Kept as idempotent DDL run at startup rather than an EF migration, matching how the rest
/// of this repo's tenant schema is maintained: the model snapshot has drifted far enough
/// that <c>dotnet ef migrations add</c> emits dozens of unrelated destructive operations.
/// Every statement is CREATE/ALTER … IF NOT EXISTS, so running it repeatedly is a no-op.
///
/// Note what is deliberately absent: no foreign key from PosAccountTransferItems to
/// BankAccountTransactions. That table is written by the personnel service too, and a
/// constraint reaching into it from here would start refusing deletes the bank screens are
/// expected to allow.
/// </summary>
public static class PosAccountSchema
{
    public const string Sql = @"
CREATE TABLE IF NOT EXISTS ""PosAccountSettings"" (
  ""Id"" integer GENERATED BY DEFAULT AS IDENTITY,
  ""PosBankAccountDefinitionId"" integer NOT NULL,
  ""TargetBankAccountDefinitionId"" integer NULL,
  ""VirtualPosBankCode"" integer NULL,
  ""TransferTime"" interval NOT NULL DEFAULT INTERVAL '1 hour',
  ""IsAutoTransferEnabled"" boolean NOT NULL DEFAULT TRUE,
  ""IsActive"" boolean NOT NULL DEFAULT TRUE,
  ""CreateUser"" character varying(50) NOT NULL DEFAULT '',
  ""CreateTime"" timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
  ""EditUser"" character varying(50) NULL,
  ""EditTime"" timestamp with time zone NULL,
  CONSTRAINT ""PK_PosAccountSettings"" PRIMARY KEY (""Id"")
);

CREATE UNIQUE INDEX IF NOT EXISTS ""IX_PosAccountSettings_PosBankAccountDefinitionId""
  ON ""PosAccountSettings"" (""PosBankAccountDefinitionId"");

-- A virtual POS provider posts into exactly one ERP account. This binding is what the
-- accounting reads, so two accounts claiming the same provider would make the destination
-- depend on row order. Partial: NULL means manual entries only, and many accounts are that.
CREATE UNIQUE INDEX IF NOT EXISTS ""IX_PosAccountSettings_VirtualPosBankCode""
  ON ""PosAccountSettings"" (""VirtualPosBankCode"") WHERE ""VirtualPosBankCode"" IS NOT NULL;

DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM information_schema.table_constraints
                 WHERE constraint_name = 'FK_PosAccountSettings_BankAccountDefinitions_Pos') THEN
    ALTER TABLE ""PosAccountSettings""
      ADD CONSTRAINT ""FK_PosAccountSettings_BankAccountDefinitions_Pos""
      FOREIGN KEY (""PosBankAccountDefinitionId"") REFERENCES ""BankAccountDefinitions"" (""Id"") ON DELETE RESTRICT;
  END IF;

  IF NOT EXISTS (SELECT 1 FROM information_schema.table_constraints
                 WHERE constraint_name = 'FK_PosAccountSettings_BankAccountDefinitions_Target') THEN
    ALTER TABLE ""PosAccountSettings""
      ADD CONSTRAINT ""FK_PosAccountSettings_BankAccountDefinitions_Target""
      FOREIGN KEY (""TargetBankAccountDefinitionId"") REFERENCES ""BankAccountDefinitions"" (""Id"") ON DELETE RESTRICT;
  END IF;
END $$;

CREATE TABLE IF NOT EXISTS ""PosAccountTransfers"" (
  ""Id"" integer GENERATED BY DEFAULT AS IDENTITY,
  ""PosBankAccountDefinitionId"" integer NOT NULL,
  ""TargetBankAccountDefinitionId"" integer NOT NULL,
  ""TransferDate"" timestamp with time zone NOT NULL,
  ""Amount"" numeric(18,2) NOT NULL DEFAULT 0.0,
  ""OutBankAccountTransactionId"" integer NULL,
  ""InBankAccountTransactionId"" integer NULL,
  ""IsAutomatic"" boolean NOT NULL DEFAULT FALSE,
  ""CreateUser"" character varying(50) NOT NULL DEFAULT '',
  ""CreateTime"" timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
  ""EditUser"" character varying(50) NULL,
  ""EditTime"" timestamp with time zone NULL,
  CONSTRAINT ""PK_PosAccountTransfers"" PRIMARY KEY (""Id"")
);

-- One sweep per account per day. This is what stops a retrying scheduler, or a second
-- server, from moving the same day's money twice.
CREATE UNIQUE INDEX IF NOT EXISTS ""IX_PosAccountTransfers_Account_Date""
  ON ""PosAccountTransfers"" (""PosBankAccountDefinitionId"", ""TransferDate"");

DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM information_schema.table_constraints
                 WHERE constraint_name = 'FK_PosAccountTransfers_BankAccountDefinitions_Pos') THEN
    ALTER TABLE ""PosAccountTransfers""
      ADD CONSTRAINT ""FK_PosAccountTransfers_BankAccountDefinitions_Pos""
      FOREIGN KEY (""PosBankAccountDefinitionId"") REFERENCES ""BankAccountDefinitions"" (""Id"") ON DELETE RESTRICT;
  END IF;

  IF NOT EXISTS (SELECT 1 FROM information_schema.table_constraints
                 WHERE constraint_name = 'FK_PosAccountTransfers_BankAccountDefinitions_Target') THEN
    ALTER TABLE ""PosAccountTransfers""
      ADD CONSTRAINT ""FK_PosAccountTransfers_BankAccountDefinitions_Target""
      FOREIGN KEY (""TargetBankAccountDefinitionId"") REFERENCES ""BankAccountDefinitions"" (""Id"") ON DELETE RESTRICT;
  END IF;
END $$;

CREATE TABLE IF NOT EXISTS ""PosAccountTransferItems"" (
  ""Id"" integer GENERATED BY DEFAULT AS IDENTITY,
  ""PosAccountTransferId"" integer NOT NULL,
  ""BankAccountTransactionId"" integer NOT NULL,
  ""Amount"" numeric(18,2) NOT NULL DEFAULT 0.0,
  ""IsLateAddition"" boolean NOT NULL DEFAULT FALSE,
  ""CreateUser"" character varying(50) NOT NULL DEFAULT '',
  ""CreateTime"" timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
  ""EditUser"" character varying(50) NULL,
  ""EditTime"" timestamp with time zone NULL,
  CONSTRAINT ""PK_PosAccountTransferItems"" PRIMARY KEY (""Id""),
  CONSTRAINT ""FK_PosAccountTransferItems_PosAccountTransfers"" FOREIGN KEY (""PosAccountTransferId"")
    REFERENCES ""PosAccountTransfers"" (""Id"") ON DELETE CASCADE
);

-- A movement belongs to at most one sweep; without this it could be counted twice.
CREATE UNIQUE INDEX IF NOT EXISTS ""IX_PosAccountTransferItems_BankAccountTransactionId""
  ON ""PosAccountTransferItems"" (""BankAccountTransactionId"");

CREATE INDEX IF NOT EXISTS ""IX_PosAccountTransferItems_PosAccountTransferId""
  ON ""PosAccountTransferItems"" (""PosAccountTransferId"");

-- Both screens live under Ayarlar (ModuleKey 'users'), beside Banka Hesap Tanım: they
-- configure where money lands, which is a settings decision, not a till operation.
UPDATE ""Pages"" SET ""ModuleKey""='users', ""SortOrder""=22
WHERE ""Key""='posHesapAyar' AND ""ModuleKey""='pos';

UPDATE ""Pages"" SET ""ModuleKey""='users', ""SortOrder""=23
WHERE ""Key""='posAktarim' AND ""ModuleKey""='pos';

INSERT INTO ""Pages"" (""DisplayName"", ""IsActive"", ""Key"", ""ModuleKey"", ""SortOrder"")
SELECT 'POS Hesap Ayarları', TRUE, 'posHesapAyar', 'users', 22
WHERE NOT EXISTS (SELECT 1 FROM ""Pages"" WHERE ""Key""='posHesapAyar');

INSERT INTO ""Pages"" (""DisplayName"", ""IsActive"", ""Key"", ""ModuleKey"", ""SortOrder"")
SELECT 'POS Aktarım', TRUE, 'posAktarim', 'users', 23
WHERE NOT EXISTS (SELECT 1 FROM ""Pages"" WHERE ""Key""='posAktarim');

-- Back office only by default. These screens decide which account a day's takings are swept
-- into; Bayi, AltBayi and Plasiyer have no business setting that, so they are not granted it
-- here. Anything beyond this is a deliberate choice made on the Rol Yetkileri screen.
-- Entering a receipt number is its own permission: reading the collection report and
-- stamping a record as receipted are different acts.
INSERT INTO ""Pages"" (""DisplayName"", ""IsActive"", ""Key"", ""ModuleKey"", ""SortOrder"")
SELECT 'Makbuz Gir', TRUE, 'posMakbuzGir', 'pos', 17
WHERE NOT EXISTS (SELECT 1 FROM ""Pages"" WHERE ""Key""='posMakbuzGir');

INSERT INTO ""RolePagePermissions"" (""RoleId"", ""PageId"", ""CanAccess"")
SELECT r.""Id"", p.""Id"", TRUE
FROM ""Roles"" r
CROSS JOIN (SELECT ""Id"" FROM ""Pages"" WHERE ""Key""='posMakbuzGir') p
WHERE r.""Id"" IN (1,2,3,7)
ON CONFLICT (""RoleId"", ""PageId"") DO NOTHING;

INSERT INTO ""RolePagePermissions"" (""RoleId"", ""PageId"", ""CanAccess"")
SELECT r.""Id"", p.""Id"", TRUE
FROM ""Roles"" r
CROSS JOIN (SELECT ""Id"" FROM ""Pages"" WHERE ""Key"" IN ('posHesapAyar','posAktarim')) p
WHERE r.""Id"" IN (1,2,3,7)
ON CONFLICT (""RoleId"", ""PageId"") DO NOTHING;
";
}
